// generate-brands.js
// Usage: node scripts/generate-brands.js  (or `npm run generate:brands`)
// Reads brand names from the back-end vendors_prefix.js (source of truth)
// and regenerates src/features/items/brands.generated.js for the Items page.

import fs from 'fs';
import path from 'path';
import { createRequire } from 'module';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);

const SOURCE_PATH = path.resolve(
  __dirname,
  '../../JustJeepsAPI-back-end/prisma/seeds/hard-code_data/vendors_prefix.js'
);
const OUTPUT_PATH = path.resolve(__dirname, '../src/features/items/brands.generated.js');

if (!fs.existsSync(SOURCE_PATH)) {
  console.warn(`[generate-brands] Source file not found, skipping: ${SOURCE_PATH}`);
  console.warn('[generate-brands] Keeping the existing brands.generated.js');
  process.exit(0);
}

const vendorsPrefix = require(SOURCE_PATH);

const seen = new Set();
const brands = [];
for (const entry of vendorsPrefix) {
  const name = (entry.brand_name || '').trim();
  if (!name || seen.has(name)) continue;
  seen.add(name);
  brands.push(name);
}

const header = `// AUTO-GENERATED FILE — do not edit manually.
// Generated by scripts/generate-brands.js from
// JustJeepsAPI-back-end/prisma/seeds/hard-code_data/vendors_prefix.js
// Regenerate with: npm run generate:brands
`;

const body = brands.map((name) => `  { brand_name: ${JSON.stringify(name)} },`).join('\n');

const content = `${header}
const brands = [
${body}
];

export default brands;
`;

fs.writeFileSync(OUTPUT_PATH, content);
console.log(`[generate-brands] Wrote ${brands.length} brands to ${OUTPUT_PATH}`);
